//! `pastel mod`: assembling the Factorio mod: its Lua sources plus every
//! recolored file, and recolored.lua, the list the mod uses to redirect
//! sprite paths.
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use anyhow::{Context, Result, bail};
use serde::Deserialize;

use crate::color::hex_to_unit;
use crate::config::value::{num, string};
use crate::manifest::Manifest;
use crate::project::Project;

/// The fields of the mod's info.json that name the mod's folder.
#[derive(Deserialize)]
struct Info {
    name: String,
    version: String,
}

/// Hard link when possible (no extra disk space), copy otherwise.
fn link_or_copy(from: &Path, to: &Path) -> Result<()> {
    if fs::hard_link(from, to).is_err() {
        fs::copy(from, to).with_context(|| format!("copying {}", from.display()))?;
    }
    Ok(())
}

/// Build `build/mod/<name>_<version>/` from the mod sources in `src` and the
/// last build's recolored files.
pub fn run(p: &Project, src: &Path) -> Result<()> {
    let info_path = src.join("info.json");
    let info: Info = serde_json::from_str(
        &fs::read_to_string(&info_path)
            .with_context(|| format!("reading {}", info_path.display()))?,
    )
    .with_context(|| format!("parsing {}", info_path.display()))?;

    let Some(manifest) = Manifest::load(&p.build_dir) else {
        bail!("No build found. Run `just build` first.");
    };
    if manifest.files.values().any(|r| !r.problems.is_empty()) {
        bail!(
            "The last build has files that failed validation (see build/build_report.csv). Fix those first."
        );
    }
    let recolored: Vec<&String> = manifest
        .files
        .iter()
        .filter(|(_, r)| r.out.is_some())
        .map(|(f, _)| f)
        .collect();
    if recolored.is_empty() {
        bail!("The last build recolored nothing. Run `just build` first.");
    }

    let dest = p
        .build_dir
        .join("mod")
        .join(format!("{}_{}", info.name, info.version));
    if dest.exists() {
        fs::remove_dir_all(&dest).with_context(|| format!("clearing {}", dest.display()))?;
    }
    for f in Project::walk_files(src) {
        let to = dest.join(&f);
        fs::create_dir_all(to.parent().unwrap())?;
        fs::copy(src.join(&f), &to).with_context(|| format!("copying {f}"))?;
    }

    // "base/graphics/entity/lab/lab.png" is stored as graphics/base/entity/lab/lab.png.
    let mut list = String::from(
        "-- Generated by `pastel mod`: every graphics file this mod recolors.\nreturn {\n",
    );
    let mut bytes = 0;
    for rel in &recolored {
        let key = rel.replacen("/graphics/", "/", 1);
        let (from, to) = (p.out_path(rel), dest.join("graphics").join(&key));
        fs::create_dir_all(to.parent().unwrap())?;
        link_or_copy(&from, &to).with_context(|| format!("{rel}: run `just build` again"))?;
        bytes += fs::metadata(&to)?.len();
        writeln!(
            list,
            "  \"{}\",",
            key.replace('\\', "\\\\").replace('"', "\\\"")
        )?;
    }
    list.push_str("}\n");
    fs::write(dest.join("recolored.lua"), list)?;
    fs::write(dest.join("liquids.lua"), liquids_lua(p)?)?;

    println!(
        "{} ({} recolored files, {:.0} MB)",
        p.show(&dest),
        recolored.len(),
        bytes as f64 / 1e6
    );
    Ok(())
}

/// A Lua string literal.
fn lua_str(s: &str) -> String {
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""))
}

/// liquids.lua: the `[liquids]` of groups that are switched on, for the mod
/// to blend each tile's shader colors toward. A liquid either names a target
/// `color` or `lighten`s each tile's own color toward white.
fn liquids_lua(p: &Project) -> Result<String> {
    let mut out =
        String::from("-- Generated by `pastel mod` from [liquids] in pastel.toml.\nreturn {\n");
    for (name, l) in p.cfg.liquids() {
        let tiles: Vec<String> = l["tiles"]
            .as_array()
            .map(|a| a.iter().filter_map(|t| t.as_str()).map(lua_str).collect())
            .unwrap_or_default();
        if tiles.is_empty() {
            bail!("liquid '{name}' in pastel.toml needs a list of `tiles`");
        }
        let target = match string(l, "color") {
            Some(hex) => {
                let [r, g, b] = hex_to_unit(hex)?;
                format!("color = {{r = {r:.4}, g = {g:.4}, b = {b:.4}}}")
            }
            None => format!("lighten = {}", num(l, "lighten", 0.5)),
        };
        writeln!(
            out,
            "  [{}] = {{tiles = {{{}}}, {target}, strength = {}}},",
            lua_str(name),
            tiles.join(", "),
            num(l, "strength", 1.0)
        )?;
    }
    out.push_str("}\n");
    Ok(out)
}
